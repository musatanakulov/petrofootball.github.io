// Проверка казахских переводов без браузера: node tests/i18n_check.js
// Подставляем минимальные «заглушки» браузера и вызываем window.i18nTranslate из i18n.js.
const assert = require('assert');
global.window = {};
global.localStorage = { getItem: (k) => (k === 'lang' ? 'kk' : null) };
global.document = { documentElement: { setAttribute() {} }, body: null, title: '', addEventListener() {} };
global.MutationObserver = class { observe() {} disconnect() {} };
require('../i18n.js');
const t = window.i18nTranslate;

const cases = [
    // вкладки и лиги
    ['Расписание', 'Кесте'], ['Результаты', 'Нәтижелер'], ['Голосование', 'Дауыс беру'], ['Вторая лига', 'Екінші лига'],
    // даты и туры внутри строк
    ['Тур 12', '12-тур'], ['сб, 28 ноября · 15:00', 'сб, 28 қараша · 15:00'], ['пн, 16 ноября', 'дс, 16 қараша'],
    ['· Тур 2 · дата уточняется', '· 2-тур · күні нақтылануда'],
    // шаблоны с числами
    ['До конца: 13 ч 59 мин', 'Аяқталуына: 13 сағ 59 мин'], ['До конца: 45 мин', 'Аяқталуына: 45 мин'],
    ['1 матч (пропущено 0 из 1)', '1 ойын (өткізілді 0/1)'], ['3 матча (пропущено 2 из 3)', '3 ойын (өткізілді 2/3)'],
    ['2 гол. (50%)', '2 дауыс (50%)'], ['Всего голосов: 4', 'Барлық дауыс: 4'],
    ['Карточек: Желтых — 0, Красных — 1', 'Карточкалар: сары — 0, қызыл — 1'],
    ['📌 Ближайший тур: Тур 2', '📌 Жақын тур: 2-тур'], ['🗳 Игрок тура — Тур 1', '🗳 Тур ойыншысы — 1-тур'],
    ['Игрок матча: Команда A 3:1 Команда B', 'Матч ойыншысы: Команда A 3:1 Команда B'],
    ['до 30.11.2026', '30.11.2026 дейін'],
    // причины, создаваемые сервером
    ['За второе предупреждение в матче', 'Ойында екінші ескерту үшін'], ['Прямая красная карточка', 'Тікелей қызыл карточка'],
];
for (const [ru, kk] of cases) assert.strictEqual(t(ru), kk, `«${ru}» -> «${t(ru)}», ожидалось «${kk}»`);

// пробелы по краям сохраняются, чужие тексты (названия команд) не трогаются
assert.strictEqual(t('  Расписание \n'), '  Кесте \n');
assert.strictEqual(t('FC Tarlan'), 'FC Tarlan');
assert.strictEqual(t('Динамо-СТЗ'), 'Динамо-СТЗ');
assert.strictEqual(t('Смирново'), 'Смирново');
console.log(`i18n: ${cases.length + 4} проверок пройдено`);
